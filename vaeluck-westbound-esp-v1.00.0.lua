	--============================================================
	-- UPDATE PLAYER
	--============================================================
	
	local function UpdatePlayer(
		player
	)
	
		if player ==
			LocalPlayer then
	
			return
		end
	
	
		local character =
			player.Character
	
	
		if not character then
			return
		end
	
	
		TrackedPlayers[
		character
		] = true
	
	
		RemoveOldSourceObjects(
			character
		)
	
	
		local anchor =
			GetCharacterAnchor(
				character
			)
	
	
		local humanoid =
			GetHumanoid(
				character
			)
	
	
		if not anchor
			or not humanoid
			or humanoid.Health <= 0 then
	
			RemovePlayerESP(
				character
			)
	
			return
		end
	
	
		local distance =
			GetDistance(
				anchor.Position
			)
	
	
		local health,
			maxHealth =
			GetHealth(
				character
			)
	
	
		local gui =
			EnsureBillboard(
	
				character,
	
				PLAYER_GUI_NAME,
	
				Settings.PlayerColor,
	
				false
			)
	
	
		UpdateBillboard(
	
			gui,
	
			GetPlayerDisplayName(
				player
			),
	
			distance,
	
			health,
	
			maxHealth,
	
			Settings.PlayerColor
		)
	
	
		EnsureHighlight(
	
			character,
	
			PLAYER_HIGHLIGHT_NAME,
	
			Settings.PlayerColor
		)
	end
	
	
