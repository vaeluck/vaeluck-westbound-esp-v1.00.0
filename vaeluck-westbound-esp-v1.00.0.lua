		local root =
			character:FindFirstChild(
				"HumanoidRootPart"
			)
	
	
		if not root then
	
			return math.huge
		end
	
	
		return (
			root.Position
			-
				position
		).Magnitude
	end
	
	
	--============================================================
	-- CLEAN GENERATED NAME
	--
	-- Removes:
	--
	-- DeerBuck{UUID}
	-- NPCName{UUID}
	-- Thing[ID]
	-- Thing(ID)
	--============================================================
	
	local function CleanGeneratedName(rawName)
	
		local name =
			tostring(rawName)
	
	
		name =
			name:gsub(
				"%b{}",
				""
			)
	
	
		name =
			name:gsub(
				"%b[]",
				""
			)
	
	
		name =
			name:gsub(
				"%b()",
				""
			)
	
	
		-- CamelCase -> Camel Case
	
		name =
			name:gsub(
				"(%l)(%u)",
				"%1 %2"
			)
	
	
		name =
			name:gsub(
				"^%s+",
				""
			)
	
	
		name =
			name:gsub(
				"%s+$",
				""
			)
	
	
		name =
			name:gsub(
				"%s+",
				" "
			)
	
	
		return name
	end
	
	
