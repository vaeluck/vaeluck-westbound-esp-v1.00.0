				if original.BackgroundTransparency ~= nil then
	
					object.BackgroundTransparency =
						1
	
				end
	
	
				if original.TextTransparency ~= nil then
	
					object.TextTransparency =
						1
	
				end
	
	
				if original.TextStrokeTransparency ~= nil then
	
					object.TextStrokeTransparency =
						1
	
				end
	
	
				if original.ImageTransparency ~= nil then
	
					object.ImageTransparency =
						1
	
				end
	
	
				if original.ScrollBarImageTransparency ~= nil then
	
					object.ScrollBarImageTransparency =
						1
	
				end
	
	
				if object:IsA("UIStroke")
					and original.Transparency ~= nil then
	
					object.Transparency =
						1
	
				end
	
			end
		end
	end
	
	
