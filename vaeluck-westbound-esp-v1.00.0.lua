	--============================================================
	
	local function EnsureBillboard(
		model,
		guiName,
		color,
		isAnimal
	)
	
		local anchor
	
		if isAnimal then
	
			anchor =
				GetRootPart(model)
	
		else
	
			anchor =
				GetCharacterAnchor(model)
	
		end
	
	
		if not anchor then
			return nil
		end
	
	
		local gui =
			model:FindFirstChild(
				guiName,
				true
			)
	
	
		if gui
			and not gui:IsA(
				"BillboardGui"
			) then
	
			gui:Destroy()
			gui = nil
		end
	
	
		if not gui then
	
			gui =
				CreateBillboard(
					guiName,
					anchor,
					color,
					isAnimal
				)
	
		else
	
			gui.Adornee =
				anchor
	
	
			if gui.Parent ~=
				anchor then
	
				gui.Parent =
					anchor
			end
	
		end
	
	
		return gui
	end
	
	
	--============================================================
	-- UPDATE BILLBOARD
	--============================================================
	
	local function UpdateBillboard(
		gui,
		displayName,
		distance,
		health,
		maxHealth,
		color
	)
	
		if not gui then
			return
		end
	
	
		local nameLabel =
			gui:FindFirstChild(
				"NameLabel"
			)
	
	
		local distanceLabel =
			gui:FindFirstChild(
				"DistanceLabel"
			)
	
	
		local healthBack =
			gui:FindFirstChild(
				"HealthBack"
			)
	
	
		local hpLabel =
			gui:FindFirstChild(
				"HPLabel"
			)
	
	
		if nameLabel then
	
			nameLabel.Text =
				displayName
	
	
			nameLabel.TextColor3 =
				color
		end
	
	
		if distanceLabel then
	
			distanceLabel.Visible =
				Settings.ShowDistance
	
	
			distanceLabel.Text =
				Settings.ShowDistance
				and (
					math.floor(distance)
					.. "m"
				)
				or ""
		end
	
	
		--========================================================
		-- HEALTH AVAILABLE
		--========================================================
	
		if health ~= nil
			and maxHealth ~= nil then
	
			maxHealth =
				math.max(
					maxHealth,
					1
				)
	
	
			local percent =
				math.clamp(
					health / maxHealth,
					0,
					1
				)
	
	
			if healthBack then
	
				healthBack.Visible =
					true
	
	
				local healthFill =
					healthBack:FindFirstChild(
						"HealthFill"
					)
	
	
				if healthFill then
	
					healthFill.Size =
						UDim2.new(
							percent,
							0,
							1,
							0
						)
	
	
					healthFill.BackgroundColor3 =
						GetHealthColor(
							percent
						)
				end
			end
	
	
			if hpLabel then
	
				hpLabel.Visible =
					true
	
	
				hpLabel.Text =
					math.floor(health)
					.. "/"
					.. math.floor(maxHealth)
			end
	
	
			--========================================================
			-- NO HEALTH DATA
			--========================================================
	
		else
	
			if healthBack then
	
				healthBack.Visible =
					false
			end
	
	
			if hpLabel then
	
				hpLabel.Visible =
					false
			end
		end
	end
	
	
